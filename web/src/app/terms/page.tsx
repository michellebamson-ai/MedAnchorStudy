import { Shell } from "@/components/shell";
import { prisma } from "@/lib/prisma";
import { getCurrentUser } from "@/lib/session";
import { isBypassOn } from "@/lib/bypass";
import { describeProvider } from "@/lib/ai/provider";

export const metadata = { title: "Terms" };
export const dynamic = "force-dynamic";

/** Terms of use. Deliberately readable, and honest about what the app is not. */
export default async function TermsPage() {
  const user = await getCurrentUser().catch(() => null);
  const topics = await prisma.topic.findMany({ orderBy: { order: "asc" } });
  const searchTopics = topics.map((t) => ({ slug: t.slug, title: t.title }));
  const providers = describeProvider();

  return (
    <Shell section="" name={user?.name ?? "Guest"} topics={searchTopics}>
      <div className="page-head">
        <span className="eyebrow">The short version</span>
        <h1 className="display">Terms</h1>
        <p className="lede">What MedAnchor Study is, and what it is not.</p>
      </div>

      <div className="legal">
        <h2>What this is</h2>
        <p>
          MedAnchor Study is an educational tool for healthcare and health-sciences students. It helps
          you study your own material, practise clinical reasoning, learn statistics, find published
          evidence and plan your revision.
        </p>

        <h2>What this is not</h2>
        <ul>
          <li>
            <b>Not medical advice.</b> Nothing here diagnoses, treats or advises on a real patient.
            Use it to learn, not to decide.
          </li>
          <li>
            <b>Not for real patient records.</b> It is not HIPAA-covered and has no clinical audit
            trail. See the <a href="/privacy">privacy page</a>.
          </li>
          <li>
            <b>Not a medical device.</b> Nothing is validated for clinical decision-making.
          </li>
          <li>
            <b>Not a substitute for your course.</b> Generated content can be wrong. Check anything
            that matters against your textbook, your lecturer or the primary source.
          </li>
        </ul>

        <h2>Accuracy, honestly</h2>
        <p>
          The app is designed not to pretend. It labels AI-generated material as such, shows its
          sources, states when a judgment rests on thin evidence, and says when a feature is not yet
          available rather than faking it. It is still an automated system that can produce confident
          errors — particularly on clinical specifics. That is why every claim should be checked
          against a primary source before you rely on it.
        </p>
        <p>
          Content is currently generated by{" "}
          <b>{providers.join(" + ")}</b>
          {providers.includes("simulated") && providers.length === 1
            ? " — the built-in offline engine, which follows fixed rules and does not learn or invent."
            : "."}
        </p>

        <h2>Your account</h2>
        <ul>
          <li>You are responsible for what happens under your account, including its password.</li>
          <li>One account per person. Please do not share logins.</li>
          <li>You can export or delete your data at any time from Settings.</li>
        </ul>

        <h2>Acceptable use</h2>
        <p>Do not use this app to:</p>
        <ul>
          <li>Store, process or upload real patient-identifiable information.</li>
          <li>Attempt to access another student&apos;s account or data.</li>
          <li>Scrape, resell or redistribute the app or its content.</li>
          <li>Upload material you do not have the right to use.</li>
        </ul>

        <h2>Availability</h2>
        <p>
          This is provided as-is, with no guarantee of uptime. Generated content depends on
          third-party AI providers; when one is unavailable the app falls back to a built-in offline
          engine and says so where it matters. Some features are labelled as not yet available rather
          than simulated.
        </p>

        <h2>Your content</h2>
        <p>
          You keep ownership of the material you upload. You grant us only the permission needed to
          store it and process it to generate study tools for you. We do not use your uploaded
          material to train models. See the <a href="/privacy">privacy page</a> for exactly what is
          sent to which provider.
        </p>

        {isBypassOn() ? (
          <div className="alert alert-warn">
            This deployment has sign-in bypassed for testing — every visitor shares one account.
          </div>
        ) : null}
      </div>
    </Shell>
  );
}
